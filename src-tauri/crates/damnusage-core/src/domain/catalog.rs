fn field(
    key: &str,
    label_key: &str,
    placeholder: &str,
    secret: bool,
    required: bool,
) -> CredentialFieldSpec {
    CredentialFieldSpec {
        key: key.to_string(),
        label_key: label_key.to_string(),
        placeholder: placeholder.to_string(),
        secret,
        required,
    }
}

